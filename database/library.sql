CREATE TABLE BOOKS (
 BOOK_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 TITLE VARCHAR2(100) NOT NULL, AUTHOR VARCHAR2(100) NOT NULL,
 CATEGORY VARCHAR2(50), QUANTITY NUMBER(5) DEFAULT 0 NOT NULL CHECK(QUANTITY >= 0)
);
CREATE TABLE STUDENTS (
 STUDENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 STUDENT_NAME VARCHAR2(100) NOT NULL, EMAIL VARCHAR2(120), PHONE VARCHAR2(15)
);
CREATE TABLE ISSUES (
 ISSUE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 BOOK_ID NUMBER NOT NULL REFERENCES BOOKS(BOOK_ID),
 STUDENT_ID NUMBER NOT NULL REFERENCES STUDENTS(STUDENT_ID),
 ISSUE_DATE DATE DEFAULT SYSDATE NOT NULL, DUE_DATE DATE NOT NULL,
 RETURN_DATE DATE, FINE NUMBER(10,2) DEFAULT 0 NOT NULL,
 FINE_PAID CHAR(1) DEFAULT 'N' CHECK(FINE_PAID IN ('Y','N')),
 CONSTRAINT CHK_ISSUE_DATES CHECK(DUE_DATE >= ISSUE_DATE)
);

CREATE OR REPLACE FUNCTION CALCULATE_FINE(P_DUE_DATE DATE, P_RETURN_DATE DATE)
RETURN NUMBER AS V_DAYS NUMBER;
BEGIN
 V_DAYS := GREATEST(TRUNC(P_RETURN_DATE)-TRUNC(P_DUE_DATE),0);
 RETURN V_DAYS*5;
END;
/

CREATE OR REPLACE PROCEDURE ADD_BOOK(P_TITLE VARCHAR2,P_AUTHOR VARCHAR2,P_CATEGORY VARCHAR2,P_QUANTITY NUMBER)
AS
BEGIN
 IF TRIM(P_TITLE) IS NULL OR TRIM(P_AUTHOR) IS NULL OR P_QUANTITY < 0 THEN
  RAISE_APPLICATION_ERROR(-20001,'Enter valid book details.');
 END IF;
 INSERT INTO BOOKS(TITLE,AUTHOR,CATEGORY,QUANTITY)
 VALUES(TRIM(P_TITLE),TRIM(P_AUTHOR),TRIM(P_CATEGORY),P_QUANTITY);
END;
/

CREATE OR REPLACE PROCEDURE ISSUE_BOOK(P_BOOK_ID NUMBER,P_STUDENT_ID NUMBER)
AS V_STOCK NUMBER; V_ACTIVE NUMBER;
BEGIN
 SELECT QUANTITY INTO V_STOCK FROM BOOKS WHERE BOOK_ID=P_BOOK_ID FOR UPDATE;
 IF V_STOCK<=0 THEN RAISE_APPLICATION_ERROR(-20002,'Book is out of stock.'); END IF;
 SELECT COUNT(*) INTO V_ACTIVE FROM ISSUES
 WHERE STUDENT_ID=P_STUDENT_ID AND RETURN_DATE IS NULL;
 IF V_ACTIVE>=3 THEN RAISE_APPLICATION_ERROR(-20003,'Student already has 3 active books.'); END IF;
 INSERT INTO ISSUES(BOOK_ID,STUDENT_ID,ISSUE_DATE,DUE_DATE)
 VALUES(P_BOOK_ID,P_STUDENT_ID,TRUNC(SYSDATE),TRUNC(SYSDATE)+14);
 UPDATE BOOKS SET QUANTITY=QUANTITY-1 WHERE BOOK_ID=P_BOOK_ID;
END;
/

CREATE OR REPLACE PROCEDURE RETURN_BOOK(P_ISSUE_ID NUMBER)
AS V_BOOK_ID NUMBER; V_DUE DATE; V_RETURN DATE; V_ALREADY DATE; V_FINE NUMBER;
BEGIN
 SELECT BOOK_ID,DUE_DATE,RETURN_DATE INTO V_BOOK_ID,V_DUE,V_ALREADY
 FROM ISSUES WHERE ISSUE_ID=P_ISSUE_ID FOR UPDATE;
 IF V_ALREADY IS NOT NULL THEN RAISE_APPLICATION_ERROR(-20004,'Already returned.'); END IF;
 V_RETURN:=TRUNC(SYSDATE);
 V_FINE:=CALCULATE_FINE(V_DUE,V_RETURN);
 UPDATE ISSUES SET RETURN_DATE=V_RETURN,FINE=V_FINE WHERE ISSUE_ID=P_ISSUE_ID;
 UPDATE BOOKS SET QUANTITY=QUANTITY+1 WHERE BOOK_ID=V_BOOK_ID;
END;
/

CREATE OR REPLACE PROCEDURE PAY_FINE(P_ISSUE_ID NUMBER)
AS V_FINE NUMBER; V_RETURN DATE;
BEGIN
 SELECT FINE,RETURN_DATE INTO V_FINE,V_RETURN FROM ISSUES
 WHERE ISSUE_ID=P_ISSUE_ID FOR UPDATE;
 IF V_RETURN IS NULL THEN RAISE_APPLICATION_ERROR(-20005,'Return book before paying fine.');
 ELSIF V_FINE=0 THEN RAISE_APPLICATION_ERROR(-20006,'No fine is due.'); END IF;
 UPDATE ISSUES SET FINE_PAID='Y' WHERE ISSUE_ID=P_ISSUE_ID;
END;
/

